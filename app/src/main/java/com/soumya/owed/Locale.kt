fun localeFor(code: String): Locale = when (code) {
    "hi" -> Locale("hi", "IN")
    "hing" -> Locale.ENGLISH
    "es" -> Locale("es")
    "fr" -> Locale("fr")
    "pt" -> Locale("pt")
    "de" -> Locale("de")
    "ar" -> Locale("ar")
    "zh" -> Locale.SIMPLIFIED_CHINESE
    "bn" -> Locale("bn")
    else -> Locale.ENGLISH
}

fun currencySymbol(code: String): String = try {
    Currency.getInstance(code).symbol
} catch (_: Exception) {
    code
}

fun t(en: String, vararg args: Any): String {
    val lang = LocaleHub.lang
    val pattern = if (lang == "en") en else Pack[lang]?.get(en) ?: en
    if (args.isEmpty()) return pattern
    return try {
        String.format(Locale.getDefault(), pattern, *args)
    } catch (_: Exception) {
        pattern
    }
}

